#!/usr/bin/env python3
"""Summarise the *measured* numbers of a real run; optionally write them into README.md section 10.

Reads only files produced by the pipeline (collection manifest, dataset metadata, COCO file, training
``metrics.json``, real-LLM auditor transcript). Nothing is estimated or typed in by hand; missing files are
reported as "not available". Writing into the README is refused when the COCO file is marked SYNTHETIC
(override with ``--allow-synthetic``), so smoke-test numbers cannot be pasted in as real results.

Usage:
    python scripts/summarize_run.py                    # print the Markdown block
    python scripts/summarize_run.py --write-readme     # replace the block between the REAL_RESULTS markers
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START, END = "<!-- REAL_RESULTS_START -->", "<!-- REAL_RESULTS_END -->"


def load(path: str | Path) -> dict | list | None:
    """Read a JSON file or return ``None`` when it does not exist."""
    p = Path(path)
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else None


def is_synthetic(coco: dict | None) -> bool:
    """True when the COCO file declares itself synthetic (see ``augle/synthetic.py``)."""
    info = (coco or {}).get("info", {})
    return "synthetic" in f"{info.get('description', '')} {info.get('contributor', '')}".lower()


def build_summary(manifest_p: str, meta_p: str, coco_p: str, metrics_p: str, llm_p: str) -> str:
    """Markdown block with every number taken from the artifacts."""
    manifest, meta, coco, metrics, llm = (load(p) for p in (manifest_p, meta_p, coco_p, metrics_p, llm_p))
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [f"_Generated by `scripts/summarize_run.py` on {stamp} from the files on disk._", ""]
    if manifest:
        s = manifest["summary"]
        lines += [
            f"**Collection** (`{manifest_p}`, source `{manifest.get('source')}`)",
            "",
            f"- candidates examined: {s['attempted']}; accepted: **{s['accepted']}**",
            f"- rejected by reason: `{json.dumps(s['rejected_by_reason'])}`",
            f"- accepted by licence: `{json.dumps(s['accepted_by_license'])}`",
            "",
        ]
    else:
        lines += [f"**Collection:** not available (`{manifest_p}` missing)", ""]
    if meta:
        a = meta["annotation"]
        lines += [
            f"**Annotation** (`{meta_p}`)",
            "",
            f"- images processed: {a['images_processed']}; with detections: **{a['images_with_detections']}**; "
            f"without detections (dropped): {a['images_without_detections']}; failed: {a['images_failed']}",
            f"- annotations: **{a['annotations']}** (with masks: {a['annotations_with_masks']}); "
            f"per category `{json.dumps(a['per_category'])}`",
            f"- detections discarded by post-processing: `{json.dumps(a['detections_dropped'])}`",
            "",
        ]
    else:
        lines += [f"**Annotation:** not available (`{meta_p}` missing)", ""]
    if coco:
        lines += [
            f"- final COCO file `{coco_p}`: **{len(coco['images'])} images**, {len(coco['annotations'])} annotations",
            "",
        ]
    if metrics:
        b, t, es = metrics["best"], metrics.get("test"), metrics["early_stopping"]
        last = metrics["history"][-1]
        lines += [
            f"**Training** (`{metrics_p}`)",
            "",
            f"- model: {metrics['model']['name']} ({metrics['model']['trainable_parameters']:,} parameters); "
            f"device `{metrics['environment']['device']}`",
            f"- splits: `{json.dumps(metrics['dataset']['split_sizes'])}`; epochs completed "
            f"{metrics['epochs_completed']}/{metrics['epochs_requested']}; early stopping triggered: {es['triggered']}",
            f"- best checkpoint: epoch **{b['epoch']}** by {b['monitor']} = {b['value']:.4f}",
            f"- last epoch {last['epoch']}: train_loss {last['train_loss']:.4f}, val_loss {last['val_loss']:.4f}, "
            f"val AP50 {last['val_ap50']:.3f}, val AP {last['val_ap']:.3f}",
        ]
        if t:
            lines.append(
                f"- held-out test (best checkpoint): loss {t['loss']:.4f}, **AP50 {t['ap50']:.3f}**, AP {t['ap']:.3f}, "
                f"per-class AP50 `{json.dumps(t['per_class_ap50'])}`"
            )
        lines += [
            "",
            "_Metrics are agreement with zero-shot pseudo-labels in the letterboxed input frame, "
            "not human-verified accuracy._",
            "",
        ]
    else:
        lines += [f"**Training:** not available (`{metrics_p}` missing)", ""]
    if llm and llm[0].get("mode") == "llm":
        lines += [
            f"**Auditor with a real LLM** (`{llm_p}`; provider `{llm[0]['provider']}`, model `{llm[0]['model']}`)",
            "",
        ]
        for answer in llm:
            tools = ", ".join(f"`{t['name']}`" + ("" if t["ok"] else " (error)") for t in answer["tool_trace"])
            lines.append(
                f"- “{answer['question'][:90]}” → tools executed: {tools or 'none'}; stop `{answer['stop_reason']}`"
            )
        lines.append("")
    else:
        lines += [f"**Auditor with a real LLM:** not available (no real-LLM transcript at `{llm_p}`)", ""]
    return "\n".join(lines)


def splice(readme: str, block: str) -> str:
    """Replace the text between the REAL_RESULTS markers with ``block``."""
    if START not in readme or END not in readme:
        raise ValueError(f"README is missing the {START} / {END} markers")
    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n{block}\n{END}{tail}"


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", default="data/raw/manifest.json")
    ap.add_argument("--dataset-meta", default="data/annotations/dataset_metadata.json")
    ap.add_argument("--coco", default="data/annotations/instances.json")
    ap.add_argument("--metrics", default="artifacts/run/metrics.json")
    ap.add_argument("--llm-transcript", default="artifacts/demo_outputs/real/auditor_demo_llm.json")
    ap.add_argument("--readme", default=str(ROOT / "README.md"))
    ap.add_argument("--write-readme", action="store_true")
    ap.add_argument("--allow-synthetic", action="store_true", help="permit writing results from a SYNTHETIC dataset")
    args = ap.parse_args(argv)
    block = build_summary(args.manifest, args.dataset_meta, args.coco, args.metrics, args.llm_transcript)
    if not args.write_readme:
        print(block)
        return 0
    if is_synthetic(load(args.coco)) and not args.allow_synthetic:
        print(
            "refusing to write README: the COCO file is marked SYNTHETIC (use --allow-synthetic to override)",
            file=sys.stderr,
        )
        return 1
    readme = Path(args.readme)
    readme.write_text(splice(readme.read_text(encoding="utf-8"), block), encoding="utf-8")
    print(f"updated {readme}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
